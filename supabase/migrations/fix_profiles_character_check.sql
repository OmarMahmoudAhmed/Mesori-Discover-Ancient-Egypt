-- ----------------------------------------------------------------
-- 1) المشكلة (الأعراض)
-- ----------------------------------------------------------------
-- عند محاولة تشغيل ملف migration الأفاتار الجديد (اللي بيغيّر قيم
-- character المسموحة من القيم القديمة (boy, girl, pharaoh, anubis,
-- scarab, ankh) للقيم الجديدة (boy, girl, Horus, Isis, Thutmose,
-- Hatshepsut))، ظهر الخطأ التالي:
--
--   ERROR: 23514: check constraint "profiles_character_check"
--   of relation "profiles" is violated by some row
--
-- ----------------------------------------------------------------
-- 2) التشخيص
-- ----------------------------------------------------------------
-- أ) فحصنا الصفوف المخالفة للقائمة القديمة فوجدنا صف واحد قيمته
--    'pharaoh' — قيمة موجودة في القائمة القديمة لكنها اتشالت من
--    القائمة الجديدة بدون ما تتحول القيمة القديمة لمكافئها الجديد
--    أولاً. القيم التانية (boy, girl) كانت متوافقة مع الاثنين.
--
-- ب) حاولنا نحدّث الصف يدويًا لقيمة 'Thutmose' لكن الخطأ استمر —
--    السبب إن ملف الـ migration كان ملفوف بالكامل في transaction
--    واحد (BEGIN...COMMIT). أول محاولة تشغيل للملف فشلت في خطوة
--    الـ ALTER TABLE، فحصل rollback تلقائي لكل حاجة جوه الـ
--    transaction — بما فيها أي DROP/ADD CONSTRAINT سابق داخل نفس
--    التشغيلة. فكان الـ constraint في القاعدة لسه بالقيم القديمة
--    فعليًا، وأي محاولة نحط 'Thutmose' (مش من القائمة القديمة)
--    كانت بترفض.
--
-- ----------------------------------------------------------------
-- 3) الحل (الخطوات اللي اتنفذت فعليًا، كل واحدة منفصلة بره أي
--    transaction كبير، عشان تنفذ وتستقر فورًا)
-- ----------------------------------------------------------------

-- الخطوة 1: شيل القيد القديم مؤقتًا عشان نقدر نصحح البيانات
-- بحرية من غير ما أي CHECK يرفض القيم الانتقالية
ALTER TABLE profiles DROP CONSTRAINT IF EXISTS profiles_character_check;

-- الخطوة 2: حوّل الصف المخالف الوحيد (كان 'pharaoh') لمكافئه
-- الجديد في نظام الأفاتار المحدث
UPDATE profiles
SET character = 'Thutmose'
WHERE id = 'b34e1948-4f32-4af4-bdd6-9f5cbf81ec2a';

-- الخطوة 3: تأكيد إن كل الصفوف بقت متوافقة مع القائمة الجديدة
-- قبل ما نعيد تفعيل القيد (لازم يرجع "Success. No rows returned")
SELECT id, character FROM profiles
WHERE character IS NULL
   OR character NOT IN ('boy', 'girl', 'Horus', 'Isis', 'Thutmose', 'Hatshepsut');

-- الخطوة 4: إعادة تفعيل القيد بالقائمة الجديدة بعد التأكد إن
-- البيانات كلها نضيفة
ALTER TABLE profiles ADD CONSTRAINT profiles_character_check
  CHECK (character IN ('boy', 'girl', 'Horus', 'Isis', 'Thutmose', 'Hatshepsut'));

-- ----------------------------------------------------------------
-- 4) بعد الخطوات دي
-- ----------------------------------------------------------------
-- تم تشغيل ملف الـ migration الأصلي كامل (004_avatar_gender_vs_mode
-- أو الاسم المكافئ له) بنجاح، لأنه:
--  - أول سطر فيه DROP CONSTRAINT IF EXISTS ملقاش حاجة يشيلها
--    (لأنها كانت اتشالت فعلاً من الخطوة 1)، فمر بسلام
--  - القيد الجديد اتضاف عادي لأن كل الصفوف كانت متوافقة بالفعل
--  - باقي الملف (عمود gender، جداول الـ 1v1 matchmaking/matches/
--    match_answers، الدوال، RLS policies، وview الـ leaderboard)
--    اتنفذ كامل من غير أي rollback

-- ----------------------------------------------------------------
-- 5) درس مهم للمستقبل (لتفادي نفس المشكلة في migrations قادمة)
-- ----------------------------------------------------------------
-- أي migration بيغيّر CHECK constraint على عمود فيه بيانات حقيقية
-- لازم يتبع الترتيب ده جوه نفس الـ migration:
--   1. UPDATE للبيانات القديمة لتتوافق مع القيم الجديدة (data
--      migration) — قبل أي تعديل على القيد
--   2. DROP CONSTRAINT
--   3. ADD CONSTRAINT بالقيم الجديدة
-- لو الـ transaction فشل في أي خطوة بعد كده، الـ rollback هيرجع
-- كل حاجة من غير ما يسيب القاعدة في حالة نص-متسقة.
